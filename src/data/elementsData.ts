// Helper to look up or construct full ElementData for any element from 1 to 118
export function getElementByNumber(num: number): ElementData {
  const detailed = ELEMENTS_DATA.find((e) => e.number === num);
  if (detailed) return detailed;

  const basic = ALL_118_ELEMENTS_SUMMARY.find((e) => e.number === num);
  if (!basic) return ELEMENTS_DATA[0]; // fallback Hydrogen

  // Derive valency description
  const valenceCount = basic.valenceElectrons;
  let valDesc = `Valence electrons: ${valenceCount}. `;
  if (basic.category === 'noble') {
    valDesc += 'Closed shell configuration (valency 0), chemically inert.';
  } else if (valenceCount <= 3) {
    valDesc += `Readily donates ${valenceCount} electron(s) to form positive cation (valency ${basic.valency.join('/')}).`;
  } else if (valenceCount === 4) {
    valDesc += 'Shares 4 electrons through covalent bonding (tetravalent).';
  } else {
    valDesc += `Gains or shares ${8 - valenceCount} electron(s) to complete stable octet (valency ${basic.valency.join('/')}).`;
  }

  return {
    number: basic.number,
    symbol: basic.symbol,
    name: basic.name,
    atomicMass: basic.atomicMass,
    category: basic.category,
    group: basic.group,
    period: basic.period,
    block: basic.block,
    shells: basic.shells,
    electronConfiguration: basic.electronConfiguration,
    electronConfigurationShort: basic.electronConfiguration,
    valency: basic.valency,
    valencyDescription: valDesc,
    valenceElectrons: basic.valenceElectrons,
    electronegativity: null,
    ionizationEnergy: null,
    phase: basic.number > 92 ? 'Synthetic' : 'Solid',
    description: `${basic.name} is a chemical element with symbol ${basic.symbol} and atomic number ${basic.number}. It resides in Group ${basic.group}, Period ${basic.period} of the periodic table.`,
    applications: ['Scientific research', 'Spectroscopic and chemical analysis'],
    quantumNumbersOuter: { n: basic.period, l: basic.block === 's' ? 0 : basic.block === 'p' ? 1 : basic.block === 'd' ? 2 : 3, ml: 0, ms: '+1/2' }
  };
}
